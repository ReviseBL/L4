import type {
  ConfrontationRequirement,
  ConfrontationScenario,
  ConfrontationSource,
} from '../../domain/confrontation/confrontation-types';

type Line = readonly [text: string, reply: string];

/**
 * Compact authoring helper: one good excuse, two bad ones.
 * Last argument limits the scene to situations where Herbi carries something
 * ('carrying') or lugs a heavy item ('heavy'); omit it for general scenes.
 */
function scenario(
  id: string,
  source: ConfrontationSource,
  opening: string,
  good: Line,
  badA: Line,
  badB: Line,
  requires?: ConfrontationRequirement,
): ConfrontationScenario {
  return {
    id,
    source,
    ...(requires ? { requires } : {}),
    opening,
    excuses: [
      { id: `${id}-good`, quality: 'good', text: good[0], reply: good[1] },
      { id: `${id}-bad-a`, quality: 'bad', text: badA[0], reply: badA[1] },
      { id: `${id}-bad-b`, quality: 'bad', text: badB[0], reply: badB[1] },
    ],
  };
}

